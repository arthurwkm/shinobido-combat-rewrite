"""Group the player's motions by action and write docs/player_motions.md.

    .venv/bin/python tools/inventory.py

Player set = every suffix-01 motion plus everything reachable through type-3 cancel targets
(formats.md "Player motion sets"). Check: each motion lands in exactly one group.
"""

import re

from extract import player_ids
from iso import ROOT
from nmt import MOTION, parse

# (group, regex on the name), first match wins. Order matters.
GROUPS = [
    ("locomotion", r"STOP\d\d|TIRED|RUN\d|RUN_|WALK_|HALT|TURN"),
    ("jumps and falls", r"JUMP|FALL|LAND|TRI_|UP_|FLIP|KICK_J|THRO_J|CLIMB_B"),
    ("rolls and evasion", r"FRONT|BACK01|RIGHT|LEFT|UKEMI"),
    ("attacks", r"AT\d|AT_|SOCCER|BLADE|KICK27|FUTO|CLAW"),
    ("guard", r"GU_"),
    ("hit reactions", r"HI_|DEKA_|NORI_|BURA_|SUI_|SHOJI_|ITEM_HI|NAGERARE"),
    ("wall, ledge and corner", r"KABE|STOP_[KABLR]\d|BACK06|ONE06|TWO06|IKOU|SHEATH_BU|STOP_ABU|HANG|CLIMB06|SHEATH06"),
    ("items and carrying", r"SHEATH01|PICK|THROW|DRINK|PUT|MAKI|NINJYUTU|OPEN|CLOSE|MAKURI"),
    ("talk and other", r"TOJO|TALK|KIME|FURI|WAIT"),
]


def player_set():
    ids = player_ids()
    inv = {v: k for k, v in ids.items()}
    seen = {n for n in ids if re.search(r"01(_H)?$", n)}
    todo = list(seen)
    while todo:
        m = parse((MOTION / f"{todo.pop()}.nmt").read_bytes())
        for _, ty, a, _ in m["events"]:
            if ty == 3 and a in inv and inv[a] not in seen:
                seen.add(inv[a])
                todo.append(inv[a])
    return sorted(seen, key=lambda n: ids[n])


def main():
    out = {g: [] for g, _ in GROUPS}
    out["other"] = []
    names = player_set()
    for n in names:
        hits = [g for g, rx in GROUPS if re.match(rx, n)]
        out[hits[0] if hits else "other"].append(n)
    assert sum(map(len, out.values())) == len(set(names)) == len(names)
    lines = ["# Player motions (generated by tools/inventory.py)", "",
             f"{len(names)} motions: suffix `01` plus those reached by type-3 cancels (formats.md). Sim status is in PROGRESS.md.", ""]
    for g, ns in out.items():
        lines += [f"## {g} ({len(ns)})", "", " ".join(ns), ""]
    (ROOT / "docs" / "player_motions.md").write_text("\n".join(lines))
    print(f"ok: {len(names)} motions, " + ", ".join(f"{g} {len(v)}" for g, v in out.items()))


if __name__ == "__main__":
    main()
