"""Parse motion\\harakiri\\C0NN.nmp packs and write docs/executions.md.

    .venv/bin/python tools/harakiri.py

Pack (little-endian): u32 count, count x (u32 motion ID, u32 offset, u32 size), motion data (a
.nmt-style blob per entry). Motion ID = 0-based mtnfile.bin index (formats.md "Execution packs").
Check: every ID names a motion and every blob lies inside the file. Writes docs/executions.md.
"""

import re
import struct
import subprocess
import sys

from extract import player_ids
from iso import ROOT
from nmt import MOTION, parse as nmt_parse

SRC = ROOT / "extracted" / "volume" / "motion" / "harakiri"


def packs():
    if not SRC.exists() or len(list(SRC.glob("C*.nmp"))) < 46:
        subprocess.run([sys.executable, str(ROOT / "tools" / "volume.py"), "extract", "motion\\harakiri\\"],
                       check=True, stdout=subprocess.DEVNULL)
    return sorted(SRC.glob("C*.nmp"))


def parse(d):
    n = struct.unpack_from("<I", d)[0]
    t = [struct.unpack_from("<3I", d, 4 + 12 * i) for i in range(n)]
    for _, off, size in t:
        assert size and off + size <= len(d), "blob outside the pack"
    return t


def main():
    ids = player_ids()
    names = {v: k for k, v in ids.items()}
    total = 0
    for p in packs():
        total += len([names[i] for i, _, _ in parse(p.read_bytes())])  # KeyError = ID outside mtnfile.bin
    # Kill reactions: KI_HI<B|C|U><...>07 (B back, C front, U above: hypothesis from the HI_ naming).
    rows = []
    for n in sorted((n for n in ids if re.fullmatch(r"KI_HI[BCUF][A-Z]*07", n)), key=ids.get):
        fr = nmt_parse((MOTION / f"{n}.nmt").read_bytes())["frames_hdr"]
        rows.append(f"| {n} | {ids[n]} | {fr} |")
    fin = [f"| {n} | {ids[n]} | {nmt_parse((MOTION / f'{n}.nmt').read_bytes())['frames_hdr']} |" for n in ("KIME_A01", "KIME_B01", "KIME_A05")]
    lines = ["# Executions (generated by tools/harakiri.py)", "",
             "`motion\\harakiri\\C001..C046.nmp` are per-stage motion libraries (formats.md \"Execution packs\"), not paired kills.",
             "No paired player/victim execution motions were found; candidates below are hypotheses (formats.md \"Executions\").", "",
             "## Victim kill reactions (enemy set `07`)", "", "| motion | ID | frames |", "|---|---|---|", *rows, "",
             "## Player finisher candidates", "", "| motion | ID | frames |", "|---|---|---|", *fin, ""]
    (ROOT / "docs" / "executions.md").write_text("\n".join(lines))
    print(f"ok: {len(packs())} packs, {total} entries, all IDs named, all blobs inside their file; {len(rows)} KI_HI reactions")


if __name__ == "__main__":
    main()
