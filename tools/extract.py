"""Write src/sim/extracted.rs: one entry per player motion (mtnfile.bin suffix 01 plus supported suffix-02 locomotion).

    python tools/extract.py        (needs extracted/volume/motion; run `python tools/volume.py extract 'motion\\'`)

Per action: name, frames, root-motion keys (frame, metres x/y/z), raw events (frame, type, arg0, arg1); frame may be slightly negative.
Keys stay raw: interpolation between them is the simulation's decision.
"""

import re

from iso import ROOT
from nmt import MOTION, parse

OUT = ROOT / "src" / "sim" / "extracted.rs"


def player_ids():
    """{name: motion ID} (0-based index in mtnfile.bin) for the player's motions."""
    d = (MOTION / "mtnfile.bin").read_bytes()
    n = int.from_bytes(d[:4], "little")
    offs = [int.from_bytes(d[4 + 4 * i : 8 + 4 * i], "little") for i in range(n)]
    return {d[o : d.index(b"\0", o)].decode()[:-4]: i for i, o in enumerate(offs)}


def player_names():
    d = (MOTION / "mtnfile.bin").read_bytes()
    n = int.from_bytes(d[:4], "little")
    offs = [int.from_bytes(d[4 + 4 * i : 8 + 4 * i], "little") for i in range(n)]
    names = [d[o : d.index(b"\0", o)].decode() for o in offs]
    return [x[:-4] for x in names if re.fullmatch(r"([A-Z_]+01|WALK_[FBRL]02|STOP02|JUMP_[FBRL]02|AT02|KICK27|FUTO27|STOP_A06|TWO06|STOP_B06|ONE06|BACK06|IKOU_B06|SHEATH06|HANG_[RL]06|CLIMB06|STOP_ABU05|IKOU_B05|SHEATH_BU05)\.nmt", x)]


def windows(events, open_t, close_t, key):
    """[(key, start, end)] pairing each open event with the next close event of the same key (frames);
    an unclosed window ends at None."""
    out, live = [], {}
    for t, ty, a, b in events:
        f = max(round(t * 60), 0)  # a few events sit 1-2 frames before the start
        if ty == open_t:
            live.setdefault(key(a, b), []).append(f)
        elif ty == close_t and live.get(key(a, b)):
            out.append((key(a, b), live[key(a, b)].pop(0), f))
    out += [(k, f, None) for k, fs in live.items() for f in fs]
    return sorted(out, key=lambda w: (w[1], w[0]))


def main():
    rows = []
    ids = player_ids()
    for name in player_names():
        m = parse((MOTION / f"{name}.nmt").read_bytes())
        assert m["tracks"], name
        root = ", ".join(f"({k[3]}, [{k[0] / 4096}, {k[1] / 4096}, {k[2] / 4096}])" for k in m["tracks"][0])
        evs = ", ".join(f"({round(t * 60)}, {ty}, {a}, {b})" for t, ty, a, b in m["events"])
        hit = ", ".join(f"({a}, {'u32::MAX' if e is None else e})" for _, a, e in windows(m["events"], 1, 2, lambda a, b: 0))
        can = ", ".join(f"({k}, {a}, {'u32::MAX' if e is None else e})" for k, a, e in windows(m["events"], 3, 4, lambda a, b: a))
        rows.append(f'    Action {{ name: "{name}", id: {ids[name]}, frames: {m["frames"]}, root: &[{root}], events: &[{evs}], hits: &[{hit}], cancels: &[{can}] }},')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/extract.py from the player's own copy of the game. Do not edit or commit.\n"
        "pub struct Action {\n    pub name: &'static str,\n    /// Motion ID: 0-based index in motion\\mtnfile.bin, as used by cancel windows.\n    pub id: u32,\n    pub frames: u32,\n"
        "    /// Root motion keys: (frame, metres). Forward is +z.\n    pub root: &'static [(u32, [f32; 3])],\n"
        "    /// Raw `.nmt` events: (frame, type, arg0, arg1); frame may be slightly negative.\n    pub events: &'static [(i32, u32, u32, u32)],\n"
        "    /// Attack-object active windows [start, end) from event types 1/2 (hypothesis, docs/formats.md); end u32::MAX = never closed.\n    pub hits: &'static [(u32, u32)],\n"
        "    /// Windows in which the game allows a transition to motion ID `.0` (event types 3/4): (id, start, end).\n    pub cancels: &'static [(u32, u32, u32)],\n}\n\n"
        "pub const ACTIONS: &[Action] = &[\n" + "\n".join(rows) + "\n];\n"
    )
    print(f"{len(rows)} actions -> {OUT}")


if __name__ == "__main__":
    main()
